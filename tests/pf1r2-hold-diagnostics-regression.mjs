import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read=name=>fs.readFileSync(new URL('../'+name,import.meta.url),'utf8');
const pipelineSrc=read('runtime-decision-pipeline.js');
const coachSrc=read('coach-integration.js');
const diagnosticsSrc=read('diagnostics.js');

const WB={optionalModules:[],emit(){},on(){},onReady(){},log(){},recordError(){}};
const window={WB};window.window=window;
vm.runInNewContext(pipelineSrc,{window,console,setTimeout,clearTimeout,Promise,Date,Error,JSON,Object,Array,Map,Set,String,Number,Math});
const P=WB.RuntimeDecisionPipeline;
assert.equal(P.version,'pf1-runtime-decision-pipeline-v1.2.2');
assert.equal(P.classifyHold(P.HOLD.NO_SEQUENCE_CANDIDATES,{stage:'P-A1',generationStatus:'UNRESOLVED',reasonCodes:['OPPONENT_WARD_UNRESOLVED']}),P.HOLD_KIND.SEMANTIC_HOLD);
assert.equal(P.classifyHold(P.HOLD.DECISION_AUTHORITY_CAPTURE_MISSING,{}),P.HOLD_KIND.AUTHORITY_HOLD);
assert.equal(P.classifyHold(P.HOLD.MODULE_UNAVAILABLE,{}),P.HOLD_KIND.SYSTEM_ERROR);
assert.equal(P.classifyHold(P.HOLD.NO_SEQUENCE_CANDIDATES,{stage:'P-C1',outcomeCount:0}),P.HOLD_KIND.SYSTEM_ERROR);

const recordedErrors=[];
const runId='run-A',windowId='window-A';
const WB2={optionalModules:[],on(){},onReady(){},log(){},emit(){},recordError(scope,err,data){recordedErrors.push({scope,message:err?.message||String(err),...data})},ReplaySession:{snapshot:()=>({analysisRun:{runId}}),clearAuthorityPresentations(){}},RuntimeAuthorityBinding:{presentationForWindow:(id,r)=>id===windowId&&r===runId?{windowId:id,runId:r}:null},RuntimeDecisionPipeline:{snapshot:()=>({items:[]})}};
const window2={WB:WB2};window2.window=window2;
vm.runInNewContext(coachSrc,{window:window2,console,setTimeout,clearTimeout,queueMicrotask,Promise,Date,Error,JSON,Object,Array,Map,Set,String,Number,Math});
const C=WB2.CoachIntegration;
assert.equal(C.version,'pe2-coach-integration-v1.2.3');
const semanticRow={status:'HOLD',holdKind:'SEMANTIC_HOLD',reason:'NO_SEQUENCE_CANDIDATES',detail:{stage:'P-A1',generationStatus:'UNRESOLVED',reasonCodes:['OPPONENT_WARD_UNRESOLVED']},meta:{runId}};
const safe=C.safeHoldDecision(semanticRow);
assert.equal(safe.meta.holdKind,'SEMANTIC_HOLD');
assert.equal(safe.meta.holdHeadline,'相手の守護が未確認のため、比較を保留しています。');
assert.ok(safe.reasonCodes.includes('OPPONENT_WARD_UNRESOLVED'));
const systemRow={status:'HOLD',holdKind:'SYSTEM_ERROR',windowId,reason:'MODULE_UNAVAILABLE',detail:{message:'missing'},meta:{runId},at:'2026-10-11T00:00:00.000Z'};
WB2.RuntimeDecisionPipeline.snapshot=()=>({items:[systemRow]});
const synced=await C.syncFromRuntime(runId);
assert.equal(synced.ingested,0);
assert.equal(synced.systemErrors,1);
assert.equal(C.snapshot().count,0);
assert.equal(recordedErrors.at(-1)?.scope,'pf1-system-hold');
assert.equal(recordedErrors.at(-1)?.holdKind,'SYSTEM_ERROR');
for(const token of ['runtimeDecisionPipelineV1','holdDiagnosticsV1','comparisonCoachV1','generationStatus','reasonCodes','holdKind'])assert.ok(diagnosticsSrc.includes(token),`diagnostics must export ${token}`);
console.log('P-F1-R2 HOLD DIAGNOSTICS REGRESSION PASS');
