import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
const duplicates=[...new Set(ids.filter((id,i)=>ids.indexOf(id)!==i))];
assert.deepEqual(duplicates,[],'HTML ids must remain unique');
for(const id of ['videoFile','video','targetSide','playOrder','scanTurns','cancelScan','turnTimeline','analyzeMatch','cancelMatch','reviewPoints','observedEpisodes','actionTimeline','exportDiag'])assert.ok(ids.includes(id),'required UI id missing: '+id);
assert.equal(html.includes('class="appTabs"'),false,'top pseudo-tabs must be removed');
assert.equal(html.includes('class="flowPanel"'),false,'non-interactive STEP cards must be removed');
assert.ok(html.includes('<h2>動画を選ぶ</h2>'));
assert.ok(html.includes('<h2>ターンを判定</h2>'));
assert.ok(html.includes('<h2>試合を振り返る</h2>'));
assert.ok(html.includes('id="analyzeMatch" class="primary" disabled>全体を振り返る</button>'));
assert.ok(html.includes('id="leAnalyzeTurn" class="legacyHidden"'),'single-turn action must remain available to code but hidden from normal UI');
assert.ok(html.includes('.uiView[data-ui-view="detail"],#scenePanel,#counterfactualPanel{display:none!important}'),'unused feature panels must be removed from normal UI without deleting their DOM contracts');
assert.ok(html.includes('--accent:#9b5de5'),'UI must use one restrained accent instead of blue-heavy styling');
assert.ok(html.includes('.primaryFlow button{width:100%;min-height:54px'),'primary CTA sizing must be consistent');
assert.ok(html.includes('id="diagnosticsPanel"'),'diagnostics must remain accessible for validation');
